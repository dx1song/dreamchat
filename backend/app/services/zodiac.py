"""太阳星座推算（根据出生月 + 日）。"""

# 每个元素：(星座名, 起始月, 起始日, 结束月, 结束日)，含摩羯座跨年边界
ZODIAC_TABLE = [
    ("摩羯座", 12, 22, 1, 19),
    ("水瓶座", 1, 20, 2, 18),
    ("双鱼座", 2, 19, 3, 20),
    ("白羊座", 3, 21, 4, 19),
    ("金牛座", 4, 20, 5, 20),
    ("双子座", 5, 21, 6, 21),
    ("巨蟹座", 6, 22, 7, 22),
    ("狮子座", 7, 23, 8, 22),
    ("处女座", 8, 23, 9, 22),
    ("天秤座", 9, 23, 10, 23),
    ("天蝎座", 10, 24, 11, 22),
    ("射手座", 11, 23, 12, 21),
]


def get_zodiac(month: int, day: int) -> str:
    """根据月份和日期返回星座名。"""
    for name, sm, sd, em, ed in ZODIAC_TABLE:
        if (month == sm and day >= sd) or (month == em and day <= ed):
            return name
    return "未知星座"
